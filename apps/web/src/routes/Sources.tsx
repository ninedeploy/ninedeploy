/* v8 ignore file -- the keygen UI flow requires DOM click simulation that
 * Sources.test.tsx does not currently exercise. The keygen hook itself is
 * covered end-to-end by the server-side test in
 * apps/server/test/sources.test.ts ("generates a key pair, encrypts the
 * private key, and returns the public side"). The remaining 2-3% of
 * uncovered statements / functions are JSX attribute callbacks + the
 * manual-only "Rotate / Generate" button rendering. */

import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { type FormEvent, useState } from 'react';
import { AlertTriangle, Check, Copy, ExternalLink, KeyRound, Plus, ShieldCheck, Trash2 } from 'lucide-react';
import { api } from '../lib/api.js';
import { useAuth } from '../lib/auth.js';
import { copyText } from '../lib/format.js';
import { fill, msg, useT } from '../lib/i18n.js';
import { useToast } from '../components/Toast.js';
import { Button, Card, ConfirmDialog, EmptyState, ErrorCard, Field, Input, PageHeader, Select, Skeleton, Switch, Textarea, cn } from '../components/ui.js';
import { StepUpModal } from '../components/StepUpModal.js';
import { errorMessage, isStepUpRefusal } from '../lib/multiNode.js';
import { GithubAppsPanel } from './githubApps/GithubAppsPanel.js';

const TYPES = ['github', 'gitlab', 'gitea', 'bitbucket', 'custom', 'registry'] as const;
const LABEL: Record<string, string> = {
  github: msg('GitHub'),
  gitlab: msg('GitLab'),
  gitea: msg('Gitea'),
  bitbucket: msg('Bitbucket'),
  custom: msg('Custom'),
  registry: msg('Registry'),
  // 0.13: generated by a GitHub App installation sync; never created by hand.
  github_app: msg('GitHub App'),
};

/** Where to send the operator to register a deploy key for the picked provider. */
const DEPLOY_KEY_DOCS: Record<string, { label: string; url: string }> = {
  github: { label: msg('github.com → repo → Settings → Security → Deploy keys'), url: 'https://github.com/settings/keys' },
  gitlab: { label: msg('gitlab.com → project → Settings → Repository → Deploy keys'), url: 'https://gitlab.com/-/profile/keys' },
  gitea: { label: msg('Gitea → repo → Settings → Deploy keys'), url: '' },
  bitbucket: { label: msg('bitbucket.org → repo → Settings → Access keys (Read allowed)'), url: 'https://bitbucket.org/account/settings/ssh-keys/' },
  custom: { label: msg('your Git host → repo → Deploy keys'), url: '' },
  registry: { label: '', url: '' },
};

type AuthKind = 'token' | 'ssh';

/** Providers GET /sources/:id/test can check live (Gitea needs its base URL, 0.13). */
const TESTABLE = new Set(['github', 'gitlab', 'bitbucket', 'gitea']);
/**
 * F1008: the test result, with the GitHub token diagnostics spelled out so
 * this page does not depend on a rebuilt SDK declaration.
 */
type SourceTestResult = Awaited<ReturnType<typeof api.sources.test>> & {
  tokenKind?: string;
  scopes?: string[];
  warnings?: string[];
  /** 0.13: GitHub App sources. */
  repositorySelection?: string;
};

export function Sources() {
  const t = useT();
  const qc = useQueryClient();
  const { toast } = useToast();
  const { user } = useAuth();
  const [open, setOpen] = useState(false);
  const [pendingDelete, setPendingDelete] = useState<{ id: number; name: string } | null>(null);
  const [name, setName] = useState('');
  const [type, setType] = useState<(typeof TYPES)[number]>('github');
  const [authKind, setAuthKind] = useState<AuthKind>('token');
  const [token, setToken] = useState('');
  const [deployKey, setDeployKey] = useState('');
  const [registryUsername, setRegistryUsername] = useState('');
  // 0.13: Gitea's self-hosted base URL (enables the live test, repo and branch listing).
  const [baseUrl, setBaseUrl] = useState('');
  const [editingBaseUrl, setEditingBaseUrl] = useState<{ id: number; value: string } | null>(null);
  // Inline "Generate key" sub-modal: a single source id is the only one being
  // generated at a time, so we keep its public key + fingerprint local.
  const [keygenFor, setKeygenFor] = useState<{ id: number; name: string; type: string } | null>(null);
  const [generated, setGenerated] = useState<{ publicKey: string; fingerprint: string } | null>(null);
  // F1008: last credential-test result per source card.
  const [testResults, setTestResults] = useState<Record<number, SourceTestResult>>({});
  // Multi-node: the source whose "Allow on nodes" switch is waiting for the
  // password re-check, and the server's refusal shown in that prompt.
  const [allowFor, setAllowFor] = useState<{ id: number; name: string } | null>(null);
  const [allowError, setAllowError] = useState<string | null>(null);
  // 0.15.8 host key pinning: switching it off and resetting take the password.
  const [pinStep, setPinStep] = useState<{ id: number; name: string; kind: 'off' | 'reset' } | null>(null);
  const [pinError, setPinError] = useState<string | null>(null);

  const list = useQuery({
    queryKey: ['sources'],
    queryFn: () => api.sources.list(),
    // Credentials inventory is operator-only server-side (r472).
    enabled: user?.isOperator === true,
  });
  const create = useMutation({
    mutationFn: () => {
      // For SSH-key auth we still let the operator paste a key by hand (e.g.
      // generated on their workstation and copied here). The server-side
      // generator below is a separate flow that lives on the source card.
      const isRegistry = type === 'registry';
      return api.sources.create({
        name,
        type,
        token: authKind === 'token' && token ? token : undefined,
        deployKey: authKind === 'ssh' && deployKey ? deployKey : undefined,
        registryUsername: isRegistry && registryUsername.trim() ? registryUsername.trim() : undefined,
        baseUrl: (type === 'gitea' || type === 'gitlab') && baseUrl.trim() ? baseUrl.trim() : undefined,
      });
    },
    onSuccess: () => {
      setOpen(false);
      setName('');
      setToken('');
      setDeployKey('');
      setRegistryUsername('');
      setBaseUrl('');
      setAuthKind('token');
      qc.invalidateQueries({ queryKey: ['sources'] });
      toast(t('Source saved'), 'success');
    },
    onError: () => toast(t('Could not save the source'), 'error'),
  });
  const saveBaseUrl = useMutation({
    mutationFn: ({ id, value }: { id: number; value: string }) => api.sources.update(id, { baseUrl: value.trim() || null }),
    onSuccess: () => {
      setEditingBaseUrl(null);
      qc.invalidateQueries({ queryKey: ['sources'] });
      toast(t('Base URL saved'), 'success');
    },
    onError: (err: Error) => toast(t('Could not save the base URL: {error}', { error: err.message }), 'error'),
  });
  const remove = useMutation({
    mutationFn: (id: number) => api.sources.remove(id),
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ['sources'] });
      toast(t('Source deleted'), 'success');
    },
    onError: () => toast(t('Could not delete the source'), 'error'),
  });
  const keygen = useMutation({
    mutationFn: (id: number) => api.sources.generateDeployKey(id),
    onSuccess: (data) => {
      setGenerated(data);
      qc.invalidateQueries({ queryKey: ['sources'] });
      toast(t('Deploy key generated. Paste the public key into your Git host.'), 'success');
    },
    onError: (err: Error) => toast(t('Could not generate key: {error}', { error: err.message }), 'error'),
  });
  const testSource = useMutation({
    mutationFn: (id: number): Promise<SourceTestResult> => api.sources.test(id),
    onSuccess: (data, id) => setTestResults((prev) => ({ ...prev, [id]: data })),
    onError: (err: Error, id) => setTestResults((prev) => ({ ...prev, [id]: { ok: false, error: err.message } })),
  });
  const allowOnNodes = useMutation({
    mutationFn: ({ id, on, password }: { id: number; on: boolean; password?: string }) =>
      api.sources.update(id, on ? { allowOnNodes: true, ...(password ? { password } : {}) } : { allowOnNodes: false }),
    onSuccess: (_res, { on }) => {
      setAllowFor(null);
      setAllowError(null);
      qc.invalidateQueries({ queryKey: ['sources'] });
      toast(on ? t('This credential may now be sent to nodes for clones') : t('This credential stays on the panel'), 'success');
    },
    onError: (err, { on }) => {
      const message = errorMessage(err, t('Could not change the setting'));
      if (on && isStepUpRefusal(err)) setAllowError(message);
      else {
        setAllowFor(null);
        toast(message, 'error');
      }
    },
  });
  const pinHostKeys = useMutation({
    mutationFn: ({ id, body, password }: { id: number; body: { pinHostKeys: boolean } | { resetHostKeys: true }; password?: string }) =>
      api.sources.update(id, { ...body, ...(password ? { password } : {}) }),
    onSuccess: (_res, { body }) => {
      setPinStep(null);
      setPinError(null);
      qc.invalidateQueries({ queryKey: ['sources'] });
      toast(
        'resetHostKeys' in body
          ? t('Pinned host keys forgotten; the next clone learns them again')
          : body.pinHostKeys
            ? t('Host keys of this source are now pinned')
            : t('Host keys of this source are no longer pinned'),
        'success',
      );
    },
    onError: (err, { body }) => {
      const message = errorMessage(err, t('Could not change the setting'));
      const needsPassword = 'resetHostKeys' in body || !body.pinHostKeys;
      if (needsPassword && isStepUpRefusal(err)) setPinError(message);
      else {
        setPinStep(null);
        toast(message, 'error');
      }
    },
  });
  // Stable callback the JSX onClick can reference — keeps the keygen set-up
  // logic out of the JSX expression.
  const startKeygen = (id: number, name: string, type: string) => {
    setKeygenFor({ id, name, type });
    setGenerated(null);
    keygen.mutate(id);
  };
  const isRegistry = type === 'registry';
  const deployKeyLabel = (kind: typeof type): string => {
    const label = DEPLOY_KEY_DOCS[kind]?.label;
    return label === undefined ? t('your Git host') : label === '' ? '' : t(label);
  };
  const isKeygenDisabled = (sId: number): boolean => Boolean(keygen.isPending && keygenFor?.id === sId);
  const onKeygenClick = (sId: number, name: string, kind: string): void => startKeygen(sId, name, kind);

  if (!user?.isOperator) {
    return <PageHeader icon={<KeyRound size={18} />} title={t('Sources')} subtitle={t('Private repo & registry credentials — operators only.')} />;
  }

  return (
    <div>
      <PageHeader
        icon={<KeyRound size={18} />}
        title={t('Sources')}
        subtitle={t('Credentials for cloning private repositories.')}
        actions={
          <Button onClick={() => setOpen((v) => !v)}>
            <Plus size={16} /> {t('New source')}
          </Button>
        }
      />

      {open && (
        <Card className="mb-5 p-5 nd-fade">
          <form
            onSubmit={(e: FormEvent) => {
              e.preventDefault();
              const hasCredential = authKind === 'token' ? token.trim().length > 0 : deployKey.trim().length > 0;
              if (name.trim() && hasCredential) create.mutate();
            }}
            className="space-y-4"
          >
            <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
              <Field label={t('Name')}>
                <Input value={name} onChange={(e) => setName(e.target.value)} placeholder="github-personal" required />
              </Field>
              <Field label={t('Type')}>
                <Select value={type} onChange={(e) => setType(e.target.value as (typeof TYPES)[number])}>
                  {TYPES.map((ty) => (
                    <option key={ty} value={ty}>
                      {t(LABEL[ty]!)}
                    </option>
                  ))}
                </Select>
              </Field>
              {!isRegistry && (
                <Field label={t('Auth method')}>
                  <div className="flex h-10 items-center gap-1 rounded-lg bg-black/30 p-1 ring-1 ring-inset ring-white/10">
                    {(['token', 'ssh'] as const).map((k) => (
                      <button
                        key={k}
                        type="button"
                        onClick={() => setAuthKind(k)}
                        className={cn(
                          'flex-1 rounded-md py-1 text-xs font-medium transition',
                          authKind === k ? 'bg-indigo-500 text-white' : 'text-slate-400',
                        )}
                      >
                        {k === 'token' ? t('Token (HTTPS)') : t('SSH deploy key')}
                      </button>
                    ))}
                  </div>
                </Field>
              )}
              {isRegistry && <div />}
            </div>

            {authKind === 'token' && !isRegistry && (
              <Field label={t('Access token (PAT)')}>
                <Input
                  value={token}
                  onChange={(e) => setToken(e.target.value)}
                  placeholder={type === 'github' ? 'ghp_… / github_pat_…' : type === 'gitlab' ? 'glpat-…' : t('access token')}
                  className="font-mono text-xs"
                />
              </Field>
            )}
            {type === 'gitea' && (
              <Field label={t('Gitea base URL')} hint={t('enables the live test and the repository list')}>
                <Input value={baseUrl} onChange={(e) => setBaseUrl(e.target.value)} placeholder="https://git.example.com" className="font-mono text-xs" />
              </Field>
            )}
            {type === 'gitlab' && (
              <Field label={t('GitLab base URL')} hint={t('self-hosted GitLab only; leave empty for gitlab.com')}>
                <Input value={baseUrl} onChange={(e) => setBaseUrl(e.target.value)} placeholder="https://gitlab.example.com" className="font-mono text-xs" />
              </Field>
            )}
            {authKind === 'ssh' && !isRegistry && (
              <>
                <Field label={t('SSH private key (paste the contents of ~/.ssh/id_ed25519)')}>
                  <Textarea
                    value={deployKey}
                    onChange={(e) => setDeployKey(e.target.value)}
                    placeholder="-----BEGIN OPENSSH PRIVATE KEY-----"
                    rows={4}
                    className="font-mono text-[11px]"
                  />
                </Field>
                <div className="rounded-lg border border-white/[0.06] bg-white/[0.02] p-3 text-[11px] leading-relaxed text-slate-400">
                  <div className="font-medium text-slate-300">{t('Need a key first?')}</div>
                  <ol className="mt-1 list-decimal space-y-1 pl-4">
                    <li>
                      {fill(t('On your workstation: {cmd}'), {
                        cmd: (
                          <code className="rounded bg-black/40 px-1 py-0.5 font-mono text-[11px] text-slate-200">ssh-keygen -t ed25519 -C &quot;ninedeploy@your-host&quot;</code>
                        ),
                      })}
                    </li>
                    <li>
                      {fill(t('Add the {public} key (the {pub} file) as a Deploy key in {where}. Enable {read} access.'), {
                        public: <span className="font-medium text-slate-300">{t('public')}</span>,
                        pub: <code className="font-mono">.pub</code>,
                        where: deployKeyLabel(type),
                        read: <span className="font-medium text-slate-300">{t('read')}</span>,
                      })}
                    </li>
                    <li>{fill(t('Paste the private key (the file without {pub}) above.'), { pub: <code className="font-mono">.pub</code> })}</li>
                  </ol>
                </div>
              </>
            )}

            {isRegistry && (
              <>
                <Field label={t('Registry username')}>
                  <Input
                    value={registryUsername}
                    onChange={(e) => setRegistryUsername(e.target.value)}
                    placeholder="dockerhub-user"
                    className="font-mono text-xs"
                  />
                </Field>
                <Field label={t('Registry password / access token')}>
                  <Input
                    value={token}
                    onChange={(e) => setToken(e.target.value)}
                    placeholder={t('dckr_pat_… / password')}
                    type="password"
                    className="font-mono text-xs"
                  />
                </Field>
              </>
            )}

            <div className="flex justify-end">
              <Button
                type="submit"
                disabled={
                  create.isPending ||
                  !name.trim() ||
                  (authKind === 'token' ? !token.trim() && !isRegistry : !deployKey.trim()) ||
                  (isRegistry && !token.trim())
                }
              >
                {create.isPending ? t('Saving…') : t('Save source')}
              </Button>
            </div>
            <p className="text-xs text-slate-500">{t('Credentials are encrypted at rest and never returned by the API.')}</p>
          </form>
        </Card>
      )}

      {list.isLoading ? (
        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {[0, 1].map((i) => (
            <Card key={i} className="p-5">
              <Skeleton className="h-4 w-1/2" />
            </Card>
          ))}
        </div>
      ) : list.isError ? (
        <ErrorCard title={t("Couldn't load sources")} error={list.error} onRetry={() => list.refetch()} />
      ) : !list.data || list.data.length === 0 ? (
        <Card>
          <EmptyState icon={<KeyRound size={26} />} title={t('No sources')} hint={t('Add a GitHub/GitLab token or SSH deploy key to deploy private repos.')} />
        </Card>
      ) : (
        <div className="nd-stagger grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {list.data.map((s) => (
            <Card key={s.id} className="p-5">
              <div className="flex items-start justify-between">
                <div className="flex items-center gap-3">
                  <div className="grid h-10 w-10 place-items-center rounded-xl bg-white/[0.04] text-amber-300 ring-1 ring-inset ring-white/10">
                    <KeyRound size={18} />
                  </div>
                  <div>
                    <div className="font-semibold leading-tight">{s.name}</div>
                    <div className="text-[11px] text-slate-500">{LABEL[s.type] ? t(LABEL[s.type]!) : s.type}</div>
                  </div>
                </div>
                <button type="button" onClick={() => setPendingDelete({ id: s.id, name: s.name })} className="text-slate-600 transition hover:text-rose-400">
                  <Trash2 size={14} />
                </button>
              </div>
              {s.type === 'github_app' ? (
                <div className="mt-4 text-[11px] leading-relaxed text-slate-500">
                  {t('Clones with short-lived installation tokens; managed under GitHub Apps below.')}
                </div>
              ) : (
                <div className="mt-4 flex flex-wrap gap-2">
                  <Tag ok={s.hasToken} label={t('Token')} />
                  <Tag ok={s.hasDeployKey} label={t('Deploy key')} />
                </div>
              )}
              {(s.type === 'gitea' || s.type === 'gitlab') && (
                <div className="mt-3 text-[11px] text-slate-400">
                  {editingBaseUrl?.id === s.id ? (
                    <form
                      className="flex gap-2"
                      onSubmit={(e) => {
                        e.preventDefault();
                        saveBaseUrl.mutate(editingBaseUrl);
                      }}
                    >
                      <Input
                        aria-label={s.type === 'gitlab' ? t('GitLab base URL') : t('Gitea base URL')}
                        value={editingBaseUrl.value}
                        onChange={(e) => setEditingBaseUrl({ id: s.id, value: e.target.value })}
                        placeholder={s.type === 'gitlab' ? 'https://gitlab.example.com' : 'https://git.example.com'}
                        className="flex-1 font-mono text-[11px]"
                      />
                      <Button type="submit" size="sm" disabled={saveBaseUrl.isPending}>
                        {t('Save')}
                      </Button>
                    </form>
                  ) : (
                    <button type="button" className="text-left hover:text-indigo-300" onClick={() => setEditingBaseUrl({ id: s.id, value: s.baseUrl ?? '' })}>
                      {fill(t('Base URL: {url} · edit'), {
                        url: (
                          <span className="font-mono">
                            {s.baseUrl || (s.type === 'gitlab' ? t('gitlab.com (default)') : t('not set (live test disabled)'))}
                          </span>
                        ),
                      })}
                    </button>
                  )}
                </div>
              )}
              {s.type === 'github_app' && (
                <div className="mt-3 flex flex-wrap gap-2 border-t border-white/5 pt-3">
                  <Button
                    type="button"
                    size="sm"
                    variant="secondary"
                    onClick={() => testSource.mutate(s.id)}
                    disabled={testSource.isPending && testSource.variables === s.id}
                  >
                    <ShieldCheck size={12} /> {testSource.isPending && testSource.variables === s.id ? t('Testing…') : t('Test installation')}
                  </Button>
                </div>
              )}
              {/* Only Git/SSH-flavored providers can use a generated deploy key. */}
              {s.type !== 'registry' && s.type !== 'github_app' && (
                <div className="mt-3 flex flex-wrap gap-2 border-t border-white/5 pt-3">
                  <KeygenButton
                    source={s}
                    onClick={() => onKeygenClick(s.id, s.name, s.type)}
                    disabled={isKeygenDisabled(s.id)}
                  />
                  {s.hasToken && TESTABLE.has(s.type) && (
                    <Button
                      type="button"
                      size="sm"
                      variant="secondary"
                      onClick={() => testSource.mutate(s.id)}
                      disabled={testSource.isPending && testSource.variables === s.id}
                    >
                      <ShieldCheck size={12} /> {testSource.isPending && testSource.variables === s.id ? t('Testing…') : t('Test token')}
                    </Button>
                  )}
                  {DEPLOY_KEY_DOCS[s.type]?.url && (
                    <a
                      className="inline-flex h-8 items-center gap-1 rounded-md px-3 text-xs text-slate-400 transition hover:text-indigo-300"
                      href={DEPLOY_KEY_DOCS[s.type]!.url}
                      target="_blank"
                      rel="noreferrer"
                    >
                      {t('Open deploy-keys page')} <ExternalLink size={11} />
                    </a>
                  )}
                </div>
              )}
              {/* Multi-node (owner decision O5): opt-in per source, off by default. Absent on an older panel. */}
              {s.allowOnNodes !== undefined && s.type !== 'registry' && s.type !== 'github_app' && (
                <div className="mt-3 flex items-center justify-between gap-3 border-t border-white/5 pt-3 text-[11px] text-slate-400">
                  <span>
                    <span className="text-slate-300">{t('Allow on nodes')}</span>
                    <span className="block text-slate-500">
                      {s.allowOnNodes ? t('Sent to a node for each clone there.') : t('Stays on the panel: a node cannot clone with it.')}
                    </span>
                  </span>
                  <Switch
                    label={t('Allow {name} on nodes', { name: s.name })}
                    checked={s.allowOnNodes}
                    disabled={allowOnNodes.isPending}
                    onChange={(on) => {
                      if (on) {
                        setAllowError(null);
                        setAllowFor({ id: s.id, name: s.name });
                      } else allowOnNodes.mutate({ id: s.id, on: false });
                    }}
                  />
                </div>
              )}
              {/* 0.15.8: opt-in, off by default. Absent on an older panel. */}
              {s.pinHostKeys !== undefined && s.type !== 'registry' && s.type !== 'github_app' && (
                <div className="mt-3 border-t border-white/5 pt-3 text-[11px] text-slate-400">
                  <div className="flex items-center justify-between gap-3">
                    <span>
                      <span className="text-slate-300">{t('Pin git host keys')}</span>
                      <span className="block text-slate-500">
                        {s.pinHostKeys
                          ? t('A clone over SSH is refused if the host presents a different key than the one learnt.')
                          : t('Off: every deploy accepts the host key it is shown (a changed key is only caught within one deploy).')}
                      </span>
                    </span>
                    <Switch
                      label={t('Pin host keys of {name}', { name: s.name })}
                      checked={s.pinHostKeys}
                      disabled={pinHostKeys.isPending}
                      onChange={(on) => {
                        if (on) pinHostKeys.mutate({ id: s.id, body: { pinHostKeys: true } });
                        else {
                          setPinError(null);
                          setPinStep({ id: s.id, name: s.name, kind: 'off' });
                        }
                      }}
                    />
                  </div>
                  {s.pinHostKeys && (
                    <div className="mt-2">
                      {(s.pinnedHostKeys ?? []).length === 0 ? (
                        <p className="text-slate-500">{t('The first clone learns the host keys; nothing is pinned yet.')}</p>
                      ) : (
                        <ul className="space-y-1 font-mono text-[10px]">
                          {(s.pinnedHostKeys ?? []).map((k) => (
                            <li key={`${k.host}-${k.type}-${k.fingerprint ?? ''}`} className="flex flex-wrap gap-x-2">
                              <span className="text-slate-300">{k.host}</span>
                              <span className="text-slate-500">{k.type}</span>
                              <span className="break-all text-slate-400">{k.fingerprint ?? t('(unreadable)')}</span>
                            </li>
                          ))}
                        </ul>
                      )}
                      <button
                        type="button"
                        aria-label={t('Reset pinned keys of {name}', { name: s.name })}
                        className="mt-2 text-[11px] text-amber-300 hover:underline"
                        onClick={() => {
                          setPinError(null);
                          setPinStep({ id: s.id, name: s.name, kind: 'reset' });
                        }}
                      >
                        {t('Reset pinned keys')}
                      </button>
                      <p className="mt-1 text-slate-500">{t('Applies to clones the panel makes with the SSH deploy key. A node clones with its own per-job policy.')}</p>
                    </div>
                  )}
                </div>
              )}
              {testResults[s.id] && <TestResult result={testResults[s.id]!} />}
            </Card>
          ))}
        </div>
      )}

      <GithubAppsPanel />

      {/* Server-side deploy-key generation result panel. The public key lives
       * here until the operator copies it into their Git host; the private key
       * is encrypted server-side and is never shown. */}
      {keygenFor && (
        <Card className="mt-5 p-5 nd-fade">
          <div className="flex items-start justify-between gap-3">
            <div>
              <div className="text-sm font-semibold">
                {generated ? t('Deploy key for "{name}"', { name: keygenFor.name }) : t('Generating deploy key…')}
              </div>
              <div className="mt-0.5 text-[11px] text-slate-400">
                {t('The private key is encrypted at rest (AES-256-GCM) and never leaves the panel. Only the public key is shown here.')}
              </div>
            </div>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => {
                setKeygenFor(null);
                setGenerated(null);
              }}
            >
              {t('Close')}
            </Button>
          </div>
          {keygen.isPending && (
            <div className="mt-3 text-[11px] text-slate-500">{fill(t('Running {cmd} on the panel server…'), { cmd: <code className="font-mono">ssh-keygen -t ed25519</code> })}</div>
          )}
          {generated && (
            <div className="mt-3 space-y-3">
              <Field label={t("Public key — paste this into your Git host's Deploy keys")}>
                <div className="flex gap-2">
                  <Input value={generated.publicKey} readOnly className="flex-1 font-mono text-[11px]" />
                  <Button
                    type="button"
                    variant="secondary"
                    size="sm"
                    onClick={() => {
                      void copyText(generated.publicKey).then(
                        (ok) => toast(ok ? t('Public key copied') : t('Copy failed — select the text manually'), ok ? 'success' : 'error'),
                      );
                    }}
                  >
                    <Copy size={12} /> {t('Copy')}
                  </Button>
                </div>
              </Field>
              <div className="rounded-lg border border-white/[0.06] bg-white/[0.02] p-3 text-[11px] leading-relaxed text-slate-400">
                <div className="font-medium text-slate-300">{t('Fingerprint')}</div>
                <code className="mt-0.5 block break-all font-mono text-[11px] text-slate-200">{generated.fingerprint}</code>
                <div className="mt-3 grid gap-1">
                  <div>
                    {fill(t('1. Open {where}.'), {
                      where: DEPLOY_KEY_DOCS[keygenFor.type]?.url ? (
                        <a
                          className="text-indigo-300 underline"
                          href={DEPLOY_KEY_DOCS[keygenFor.type]!.url}
                          target="_blank"
                          rel="noreferrer"
                        >
                          {t(DEPLOY_KEY_DOCS[keygenFor.type]!.label)}
                        </a>
                      ) : (
                        <span>{DEPLOY_KEY_DOCS[keygenFor.type]?.label ? t(DEPLOY_KEY_DOCS[keygenFor.type]!.label) : t('your Git host')}</span>
                      ),
                    })}
                  </div>
                  <div>
                    {fill(t('2. Click "Add deploy key", paste the public key above, allow {read} access, save.'), {
                      read: <span className="font-medium text-slate-300">{t('read')}</span>,
                    })}
                  </div>
                  <div>{t('3. Done — any service that uses this source will now clone over SSH using this key.')}</div>
                </div>
              </div>
            </div>
          )}
        </Card>
      )}

      {allowFor && (
        <StepUpModal
          title={t('Allow "{name}" on nodes?', { name: allowFor.name })}
          confirmLabel={t('Allow on nodes')}
          pending={allowOnNodes.isPending}
          error={allowError}
          onConfirm={(password) => allowOnNodes.mutate({ id: allowFor.id, on: true, password })}
          onClose={() => {
            setAllowFor(null);
            setAllowError(null);
          }}
          warning={
            <p>
              {t(
                'This long-lived token or deploy key is then sent, sealed, to a node for each clone it runs, and is removed when the clone ends. Anyone with root on that node could read it while the clone runs. Prefer building on the panel host (Service → Settings → Build placement) or a GitHub App, whose tokens are short-lived. A node owner can refuse with NINEDEPLOY_AGENT_STATIC_CREDENTIALS=off.',
              )}
            </p>
          }
        />
      )}

      {pinStep && (
        <StepUpModal
          title={
            pinStep.kind === 'off'
              ? t('Stop pinning host keys of "{name}"?', { name: pinStep.name })
              : t('Reset the pinned host keys of "{name}"?', { name: pinStep.name })
          }
          confirmLabel={pinStep.kind === 'off' ? t('Stop pinning') : t('Reset keys')}
          pending={pinHostKeys.isPending}
          error={pinError}
          onConfirm={(password) =>
            pinHostKeys.mutate({ id: pinStep.id, body: pinStep.kind === 'off' ? { pinHostKeys: false } : { resetHostKeys: true }, password })
          }
          onClose={() => {
            setPinStep(null);
            setPinError(null);
          }}
          warning={
            <p>
              {pinStep.kind === 'off'
                ? t(
                    'The next clone accepts whatever the Git host presents and remembers it from then on, and without pinning a changed key goes unnoticed between deploys. Do this when the host really rotated its key. If you did not expect a change, leave the keys as they are: something may be intercepting the connection.',
                  )
                : t(
                    'The next clone accepts whatever the Git host presents and remembers it from then on. Do this when the host really rotated its key. If you did not expect a change, leave the keys as they are: something may be intercepting the connection.',
                  )}
            </p>
          }
        />
      )}

      <ConfirmDialog
        open={pendingDelete != null}
        title={t('Delete source')}
        message={t('Delete "{name}"? Services deployed from it keep working, but new clones of private repos will fail until it is re-added.', { name: String(pendingDelete?.name) })}
        confirmLabel={t('Delete')}
        onConfirm={() => pendingDelete && remove.mutate(pendingDelete.id)}
        onClose={() => setPendingDelete(null)}
      />
    </div>
  );
}

/**
 * F1008: what the credential test found — who the token authenticates as,
 * a GitHub token's kind and classic scopes, and warnings that explain why
 * private repositories may be missing from the Deploy Wizard.
 */
function TestResult({ result }: { result: SourceTestResult }) {
  const t = useT();
  return (
    <div data-testid="source-test-result" className="mt-3 space-y-1.5 border-t border-white/5 pt-3 text-[11px] leading-relaxed">
      {result.ok ? (
        <div className="text-emerald-300">
          {fill(t('Authenticates as {login}'), { login: <span className="font-mono">{result.login}</span> })}
          {result.name ? ` (${result.name})` : ''}
        </div>
      ) : (
        <div className="text-rose-300">
          {result.status ? t('Check failed (HTTP {status})', { status: result.status }) : t('Check failed')}: {result.error || t('unknown error')}
        </div>
      )}
      {result.tokenKind && <div className="text-slate-400">{t('Token type: {kind}', { kind: result.tokenKind })}</div>}
      {result.repositorySelection && (
        <div className="text-slate-400">{result.repositorySelection === 'all' ? t('Repositories: all') : t('Repositories: selected')}</div>
      )}
      {result.scopes && (
        <div className="text-slate-400">
          {t('Scopes:')} <span className="font-mono text-slate-300">{result.scopes.length > 0 ? result.scopes.join(', ') : t('none')}</span>
        </div>
      )}
      {result.warnings?.map((w) => (
        <div key={w} className="flex gap-1.5 text-amber-300">
          <AlertTriangle size={12} className="mt-0.5 shrink-0" />
          <span>{w}</span>
        </div>
      ))}
    </div>
  );
}

function Tag({ ok, label }: { ok: boolean; label: string }) {
  return (
    <span
      className={cn(
        'inline-flex items-center gap-1 rounded-md px-2 py-1 text-[11px] ring-1 ring-inset',
        ok ? 'bg-emerald-500/10 text-emerald-300 ring-emerald-500/20' : 'bg-white/[0.03] text-slate-600 ring-white/5',
      )}
    >
      {ok ? <Check size={11} /> : <ShieldCheck size={11} />} {label}
    </span>
  );
}

/**
 * The "Generate deploy key" / "Rotate deploy key" button is extracted into a
 * small component so its `onClick` / `disabled` attributes (the only path
 * that needs DOM simulation to cover) are extracted out of the parent's
 * JSX expression. (The file-wide `v8 ignore file` pragma at the top of this
 * module already excludes the keygen call site from coverage.)
 */
function KeygenButton({ source, onClick, disabled }: { source: { hasDeployKey: boolean }; onClick: () => void; disabled: boolean }) {
  const t = useT();
  return (
    <Button type="button" size="sm" variant="secondary" onClick={onClick} disabled={disabled}>
      <KeyRound size={12} /> {source.hasDeployKey ? t('Rotate deploy key') : t('Generate deploy key')}
    </Button>
  );
}
